/**
 * Shared A4 document scaffolding for every report type (V2.5 section 7): restrained header with GeoSolver
 * branding + project name, footer with generation timestamp + page numbers, a title block, and a consistent
 * clean table style (thin horizontal rules only, no heavy decoration). pdfmake repeats a table's `headerRows`
 * automatically across a page break, satisfying "tables with repeated headers across pages" without extra code.
 */
const { fmtDateTime } = require('../formatting');

const PAGE_MARGINS = [40, 58, 40, 46];

function header(model, bg) {
  return (currentPage) => ({
    margin: [40, 18, 40, 0],
    stack: [
      {
        columns: [
          { text: 'GeoSolver', bold: true, fontSize: 10, color: '#3a3a3a' },
          { text: model.project.name, alignment: 'right', fontSize: 9, color: '#3a3a3a' },
        ],
      },
      { canvas: [{ type: 'line', x1: 0, y1: 6, x2: 515, y2: 6, lineWidth: 0.75, lineColor: '#cfcfcf' }] },
    ],
  });
}

function footer(model, bg) {
  return (currentPage, pageCount) => ({
    margin: [40, 8, 40, 0],
    columns: [
      { text: `${bg ? 'Генериран' : 'Generated'}: ${fmtDateTime(model.generatedAt, bg)}`, fontSize: 7, color: '#8a8a8a' },
      { text: `${bg ? 'Страница' : 'Page'} ${currentPage} / ${pageCount}`, alignment: 'right', fontSize: 7, color: '#8a8a8a' },
    ],
  });
}

function titleBlock(model, bg) {
  const noLabel = bg ? 'No' : 'No';
  return [
    { text: model.title, style: 'title' },
    {
      columns: [
        { text: [{ text: `${bg ? 'Проект' : 'Project'}: `, bold: true }, model.project.name] },
        model.documentNumber
          ? { text: [{ text: `${noLabel}: `, bold: true }, String(model.documentNumber)], alignment: 'right' }
          : { text: '' },
      ],
      margin: [0, 4, 0, 0],
      fontSize: 9,
    },
    {
      columns: [
        { text: [{ text: `${bg ? 'Дата на генериране' : 'Generated'}: `, bold: true }, fmtDateTime(model.generatedAt, bg)] },
        { text: [{ text: `${bg ? 'Изготвил' : 'Generated by'}: `, bold: true }, model.generatedBy.name], alignment: 'right' },
      ],
      margin: [0, 2, 0, 14],
      fontSize: 8.5,
    },
  ];
}

const styles = {
  title: { fontSize: 16, bold: true, margin: [0, 0, 0, 8] },
  h2: { fontSize: 11, bold: true, margin: [0, 12, 0, 6], color: '#111111' },
  tableHeader: { bold: true, fontSize: 7.5, fillColor: '#f2f2f2' },
  cell: { fontSize: 8 },
  small: { fontSize: 7.5, color: '#666666' },
  note: { fontSize: 8, color: '#a15c00', margin: [0, 2, 0, 2] },
};

/** A clean, professional table style: thin horizontal rules only, no vertical lines, tight padding. */
const tableLayout = {
  hLineWidth: (i, node) => (i === 0 || i === 1 || i === node.table.body.length ? 0.75 : 0.4),
  vLineWidth: () => 0,
  hLineColor: () => '#c9c9c9',
  paddingLeft: () => 4,
  paddingRight: () => 4,
  paddingTop: () => 2,
  paddingBottom: () => 2,
};

function buildDocument({ model, bg = true, content }) {
  return {
    pageSize: 'A4',
    pageMargins: PAGE_MARGINS,
    header: header(model, bg),
    footer: footer(model, bg),
    defaultStyle: { font: 'NotoSans', fontSize: 9, lineHeight: 1.15 },
    styles,
    content: [...titleBlock(model, bg), ...content],
    info: { title: model.title, author: 'GeoSolver' },
  };
}

module.exports = { buildDocument, styles, tableLayout, PAGE_MARGINS };
