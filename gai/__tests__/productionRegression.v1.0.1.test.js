/**
 * V1.0.1 production fix: reproduces the exact real-world project shape from the first live GAI answer - many
 * SurveyPoints, legacy digital carnets (models/FieldBook.js), and ZERO CaptureJobs in the new system - and asserts
 * the three grounding/UX issues found there are actually fixed:
 *   1. no raw Mongo ObjectId ever reaches the LLM prompt (buildContext.js#stripInternalIds)
 *   2. capture.total === 0 is never conflated with "no field data" when legacyFieldBooks exist
 *   3. the system prompt instructs against unsupported absolute claims (checked at the prompt-text level, since
 *      the actual prose is generated by a live LLM we never call in tests - see gai/prompt/__tests__)
 */
jest.mock('../../models/SurveyPoint', () => require('../../tests/support/fakeCaptureModels').SurveyPoint);
jest.mock('../../models/CaptureJob', () => require('../../tests/support/fakeCaptureModels').CaptureJob);
jest.mock('../../models/FieldObservationSet', () => require('../../tests/support/fakeCaptureModels').FieldObservationSet);
jest.mock('../../models/FieldProcessingRun', () => require('../../tests/support/fakeCaptureModels').FieldProcessingRun);
jest.mock('../../models/Report', () => require('../../tests/support/fakeCaptureModels').Report);
jest.mock('../../models/Calculation', () => require('../../tests/support/fakeCaptureModels').Calculation);
jest.mock('../../models/FieldBook', () => require('../../tests/support/fakeCaptureModels').FieldBook);
jest.mock('../../models/FieldSession', () => require('../../tests/support/fakeCaptureModels').FieldSession);
jest.mock('../../models/FieldBookProject');

const SurveyPoint = require('../../models/SurveyPoint');
const CaptureJob = require('../../models/CaptureJob');
const FieldObservationSet = require('../../models/FieldObservationSet');
const FieldProcessingRun = require('../../models/FieldProcessingRun');
const Report = require('../../models/Report');
const Calculation = require('../../models/Calculation');
const FieldBook = require('../../models/FieldBook');
const FieldBookProject = require('../../models/FieldBookProject');
const { newId } = require('../../tests/support/fakeCaptureModels');
const { buildContext, formatContextForPrompt } = require('../context/buildContext');
const { getProjectSummary } = require('../tools/projectSummary');
const { answerQuestion } = require('../service');
const { setProviderForTests } = require('../provider');
const { fakeGaiProvider } = require('../../tests/support/fakeGaiProvider');

const PROJECT = newId(); // a REAL ObjectId-shaped id - 'proj1'-style fixtures elsewhere wouldn't catch this bug
const USER = newId();
const OBJECT_ID_PATTERN = /\b[0-9a-f]{24}\b/i;

const ORIGINAL_GAI_V1_ENABLED = process.env.GAI_V1_ENABLED;

beforeEach(() => {
  SurveyPoint.__reset();
  CaptureJob.__reset();
  FieldObservationSet.__reset();
  FieldProcessingRun.__reset();
  Report.__reset();
  Calculation.__reset();
  FieldBook.__reset();
  FieldBookProject.findById.mockImplementation(async (id) =>
    (String(id) === PROJECT ? { _id: PROJECT, name: 'Обект Стара Загора', crs: 'EPSG:7801' } : null));
  process.env.GAI_V1_ENABLED = 'true';
});
afterEach(() => { process.env.GAI_V1_ENABLED = ORIGINAL_GAI_V1_ENABLED; });

/** Seeds the exact production shape: 31 SurveyPoints, 2 legacy Field Books, zero Capture jobs. */
async function seedProductionShape() {
  for (let i = 0; i < 31; i += 1) {
    // eslint-disable-next-line no-await-in-loop
    await SurveyPoint.create({ user: USER, projectId: PROJECT, name: String(100 + i), x: 1000 + i, y: 2000 + i, h: 500 });
  }
  await FieldBook.create({ user: USER, project: PROJECT, name: 'Карнет 1', type: 'coordinate' });
  await FieldBook.create({ user: USER, project: PROJECT, name: 'Карнет 2', type: 'leveling' });
  // deliberately zero CaptureJobs - that is the whole point of this fixture
}

describe('V1.0.1 regression: 31 points, 2 legacy Field Books, 0 Capture jobs', () => {
  it('getProjectSummary reports pointCount=31, capture.total=0, AND legacyFieldBooks.total=2 - never collapses them', async () => {
    await seedProductionShape();
    const summary = await getProjectSummary(PROJECT);
    expect(summary.pointCount).toBe(31);
    expect(summary.capture.total).toBe(0);
    expect(summary.legacyFieldBooks).toEqual({ total: 2, active: 2, byType: { coordinate: 1, leveling: 1 } });
  });

  it('buildContext for "Обобщи проекта" carries both signals so the LLM cannot say "no field data" from capture.total alone', async () => {
    await seedProductionShape();
    const ctx = await buildContext({ projectId: PROJECT, userId: USER, question: 'Обобщи проекта' });
    expect(ctx.data.projectSummary.capture.total).toBe(0);
    expect(ctx.data.projectSummary.legacyFieldBooks.total).toBe(2);
  });

  it('no raw Mongo ObjectId reaches the rendered prompt context, even though project/point/fieldbook ids are real ObjectIds', async () => {
    await seedProductionShape();
    const ctx = await buildContext({ projectId: PROJECT, userId: USER, question: 'Обобщи проекта' });
    const rendered = formatContextForPrompt(ctx);

    // sanity: the RAW (unstripped) data really does contain real ObjectIds, proving this test is not vacuous
    expect(OBJECT_ID_PATTERN.test(JSON.stringify(ctx.data))).toBe(true);
    // but the rendered, LLM-facing prompt context must not
    expect(OBJECT_ID_PATTERN.test(rendered)).toBe(false);
    expect(rendered).not.toContain(PROJECT);
  });

  it('end-to-end via answerQuestion: neither the system prompt nor the user content sent to the provider contains a raw Mongo id', async () => {
    await seedProductionShape();
    const provider = fakeGaiProvider({ reply: 'Обобщение на проекта.' });
    setProviderForTests('openai', provider);

    const result = await answerQuestion({ projectId: PROJECT, userId: USER, question: 'Обобщи проекта' });

    expect(provider.calls).toHaveLength(1);
    const { system, messages } = provider.calls[0];
    expect(OBJECT_ID_PATTERN.test(system)).toBe(false);
    expect(OBJECT_ID_PATTERN.test(messages[0].content)).toBe(false);
    // the user-facing answer itself (here, the fixture's canned reply - never a live LLM) is also clean
    expect(OBJECT_ID_PATTERN.test(result.text)).toBe(false);

    setProviderForTests('openai', null);
  });

  it('the system prompt forbids internal identifiers and unsupported absolute claims - without naming internals itself', () => {
    // V1.0.2: the V1.0.1 prompt named the internal fields it warned about, which made the live model echo them.
    const { SYSTEM_PROMPT, PROMPT_VERSION } = require('../prompt/systemPrompt');
    const { FORBIDDEN_PROVIDER_TERMS } = require('../terminology');
    expect(PROMPT_VERSION).toBe('gai-v1.0.2');
    expect(SYSTEM_PROMPT).toMatch(/вътрешни идентификатори/);
    expect(SYSTEM_PROMPT).toMatch(/БЕЗ НЕОБОСНОВАНИ ТВЪРДЕНИЯ/);
    expect(SYSTEM_PROMPT).toMatch(/Не откривам елементи със статус „За проверка“|не откривам елементи със статус „За проверка“/);
    for (const term of FORBIDDEN_PROVIDER_TERMS) {
      expect(SYSTEM_PROMPT).not.toMatch(new RegExp(`(^|[^A-Za-z_])${term}([^A-Za-z_]|$)`));
    }
  });
});
