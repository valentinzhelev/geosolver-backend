/**
 * Deterministic OCR digit/character confusion knowledge (pure, no I/O).
 *
 * This module NEVER repairs a value. It only explains why two candidate readings of the same cell might differ
 * (so the arbitration layer and the review UI can say "these differ at position 5, a common 0/8 confusion") and,
 * for the specific letter<->digit look-alikes (O<->0, I/l<->1), proposes bounded GENERATED alternative readings.
 * A generated alternative is tagged `source: 'generated-alternative'` and the arbitration layer (arbitration.js)
 * is forbidden from accepting a cell on the strength of a generated alternative alone: it may only raise a value
 * to REVIEW_SUGGESTED, never to ACCEPTED. See capture/arbitration.js.
 */

// Digit families that are commonly confused by OCR on printed/handwritten digits. Membership in the same family
// does not mean "these are interchangeable"; it means a mismatch there is a well-known confusion, not a wild guess.
const DIGIT_FAMILIES = [
  ['0', '6', '8', '9'],
  ['1', '7'],
  ['3', '8'],
  ['4', '9'],
  ['5', '6'],
];

const DIGIT_FAMILY_OF = new Map();
for (const family of DIGIT_FAMILIES) {
  for (const d of family) {
    const set = DIGIT_FAMILY_OF.get(d) || new Set();
    family.forEach((x) => x !== d && set.add(x));
    DIGIT_FAMILY_OF.set(d, set);
  }
}

/** Letter <-> digit look-alikes. Each entry: the letter, and the single digit it may stand for. Case-sensitive keys. */
const LETTER_DIGIT_LOOKALIKES = [
  { letter: 'O', digit: '0' },
  { letter: 'o', digit: '0' },
  { letter: 'I', digit: '1' },
  { letter: 'l', digit: '1' },
];
const LOOKALIKE_BY_LETTER = new Map(LETTER_DIGIT_LOOKALIKES.map((x) => [x.letter, x.digit]));

/** Are two digit characters members of a known OCR confusion family? (order-independent, false for identical chars) */
function isDigitConfusionPair(a, b) {
  if (a === b) return false;
  const set = DIGIT_FAMILY_OF.get(a);
  return Boolean(set && set.has(b));
}

/**
 * Position-by-position comparison of two same-length strings (typically two normalized numeric readings' digit
 * strings). Returns the mismatched positions, each flagged with whether it is a known OCR confusion pair.
 * Different-length strings are reported as a single non-positional mismatch (`aligned: false`).
 */
function compareDigitStrings(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string' || a.length !== b.length) {
    return { aligned: false, mismatches: [] };
  }
  const mismatches = [];
  for (let i = 0; i < a.length; i += 1) {
    if (a[i] !== b[i]) mismatches.push({ index: i, from: a[i], to: b[i], knownConfusion: isDigitConfusionPair(a[i], b[i]) });
  }
  return { aligned: true, mismatches };
}

/**
 * Bounded, explicit letter->digit alternative readings for a raw OCR text. Only the known look-alikes are ever
 * substituted; every other character is left untouched. Returns [] when the text has no look-alike letters, or
 * when substituting them would still leave non-numeric characters (the cell is not "almost numeric").
 * @param {string} rawText
 * @param {{maxAlternatives?: number}} options
 * @returns {string[]} candidate alternative texts, most-substitutions-first is NOT implied: only one alternative
 *   (all look-alikes replaced at once) is generated by default, kept simple and bounded.
 */
function generateLetterDigitAlternatives(rawText, options = {}) {
  const maxAlternatives = options.maxAlternatives ?? 4;
  const text = String(rawText || '');
  if (!text) return [];
  const letterPositions = [...text].map((ch, i) => ({ ch, i })).filter(({ ch }) => LOOKALIKE_BY_LETTER.has(ch));
  if (!letterPositions.length) return [];
  // a candidate is only worth proposing if, once digit-substituted, the text becomes plausibly numeric (digits and
  // the usual separators only) - otherwise we would be "inventing" a reading with no numeric justification.
  const substituted = [...text].map((ch) => (LOOKALIKE_BY_LETTER.has(ch) ? LOOKALIKE_BY_LETTER.get(ch) : ch)).join('');
  if (!/^[+-]?[0-9 .,']+$/.test(substituted)) return [];
  const alternatives = [substituted];
  // one-at-a-time substitutions too (bounded), in case only ONE look-alike is really a digit and the rest is text
  for (const { i } of letterPositions) {
    if (alternatives.length >= maxAlternatives) break;
    const chars = [...text];
    chars[i] = LOOKALIKE_BY_LETTER.get(chars[i]);
    const candidate = chars.join('');
    if (candidate !== substituted && !alternatives.includes(candidate)) alternatives.push(candidate);
  }
  return alternatives.slice(0, maxAlternatives);
}

module.exports = { DIGIT_FAMILIES, isDigitConfusionPair, compareDigitStrings, generateLetterDigitAlternatives, LOOKALIKE_BY_LETTER };
